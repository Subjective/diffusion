"""Rule-based detection of files a reviewer can safely skip, decided before any model call."""

from __future__ import annotations

import fnmatch
from typing import Literal

from .hunks import FileDiff

SkipReason = Literal["lockfile", "generated", "snapshot", "vendored", "rename", "binary"]

_LOCKFILES = {
    "package-lock.json", "yarn.lock", "pnpm-lock.yaml", "bun.lockb", "poetry.lock", "uv.lock", "Pipfile.lock",
    "Cargo.lock", "go.sum", "Gemfile.lock", "composer.lock", "flake.lock", "pdm.lock", "conda-lock.yml",
}  # fmt: skip
_GENERATED = [
    "*.min.js", "*.min.css", "*.map", "*_pb2.py", "*_pb2.pyi", "*_pb2_grpc.py",
    "*.pb.go", "*.pb.cc", "*.pb.h", "*.generated.*", "*.gen.go", "*.g.dart", "*.designer.cs",
    "dist/*", "build/*", "*/dist/*", "*/build/*",
]  # fmt: skip
_SNAPSHOT = ["*.snap", "*/__snapshots__/*", "*/snapshots/*", "*.ambr"]
_VENDORED = [
    "vendor/*",
    "*/vendor/*",
    "third_party/*",
    "*/third_party/*",
    "node_modules/*",
    "*/node_modules/*",
]
_GENERATED_MARKERS = ("@generated", "DO NOT EDIT", "Code generated by", "autogenerated")


def _match(path: str, patterns: list[str]) -> bool:
    return any(fnmatch.fnmatch(path, p) for p in patterns)


def _generated_header(f: FileDiff) -> bool:
    if not f.hunks or f.hunks[0].new_start > 1:
        return False
    head = " ".join(ln.text for ln in f.hunks[0].lines[:5] if ln.type != "del")
    return any(m in head for m in _GENERATED_MARKERS)


def classify(f: FileDiff) -> SkipReason | None:
    name = f.path.rsplit("/", 1)[-1]
    if f.binary:
        return "binary"
    if f.pure_rename:
        return "rename"
    if name in _LOCKFILES:
        return "lockfile"
    if _match(f.path, _SNAPSHOT):
        return "snapshot"
    if _match(f.path, _VENDORED):
        return "vendored"
    if _match(f.path, _GENERATED) or _generated_header(f):
        return "generated"
    return None
