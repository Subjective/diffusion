import pytest

from diffusion.classify import classify
from diffusion.hunks import FileDiff, Hunk, Line, parse_diff


@pytest.fixture
def index(checkout):
    return parse_diff(checkout.diff())


def test_files_and_statuses(index):
    by = {f.path: f for f in index.files}
    assert by["src/auth/session.ts"].status == "modified"
    assert by["tests/session.test.ts"].status == "added"
    assert by["src/legacy.ts"].status == "deleted"
    assert by["docs/guide.md"].status == "renamed"
    assert by["docs/guide.md"].old_path == "docs/notes.md"
    assert by["docs/guide.md"].pure_rename
    assert by["assets/logo.png"].binary


def test_ids_are_sequential_and_stable(checkout, index):
    ids = [h.id for h in index.hunks]
    assert ids == [f"H{i}" for i in range(1, len(ids) + 1)]
    again = parse_diff(checkout.diff())
    assert [(h.id, h.file, h.new_start) for h in again.hunks] == [
        (h.id, h.file, h.new_start) for h in index.hunks
    ]
    assert index.by_id["H1"] is index.hunks[0]


def test_line_numbers(index):
    types = next(h for h in index.hunks if h.file == "src/auth/types.ts")
    added = [ln for ln in types.lines if ln.type == "add"]
    assert [(ln.new, ln.text) for ln in added] == [(4, "  expiresAt: number;")]
    assert all(ln.old is None for ln in added)
    ctx = [ln for ln in types.lines if ln.type == "ctx"]
    assert all(ln.old is not None and ln.new is not None for ln in ctx)


def test_deletion_only_hunk(index):
    legacy = index.file("src/legacy.ts")
    (h,) = legacy.hunks
    assert h.new_len == 0 and h.deletions == 1 and h.additions == 0
    assert h.lines[0].type == "del" and h.lines[0].old == 1


def test_annotated_and_table(index):
    h = next(h for h in index.hunks if h.file == "src/auth/types.ts")
    text = h.annotated()
    assert text.startswith(f"[{h.id}] src/auth/types.ts @@")
    assert "    4       +   expiresAt: number;" in text
    assert f"{h.id}  src/auth/types.ts  +" in index.table()


def test_to_dict_roundtrips_shape(index):
    d = index.to_dict()
    f = next(f for f in d["files"] if f["hunks"])
    assert {"path", "status", "hunks", "additions", "deletions"} <= f.keys()
    assert {"id", "lines", "symbol"} <= f["hunks"][0].keys()


def _fd(path, first_line="x", **kw):
    hunk = Hunk("H1", path, 0, 0, 1, 1, "", [Line("add", None, 1, first_line)])
    return FileDiff(path, None, kw.pop("status", "modified"), kw.pop("binary", False), 1, 0, [hunk], **kw)


@pytest.mark.parametrize(
    "path,reason",
    [
        ("package-lock.json", "lockfile"),
        ("web/pnpm-lock.yaml", "lockfile"),
        ("engine/uv.lock", "lockfile"),
        ("src/auth/__snapshots__/session.test.ts.snap", "snapshot"),
        ("api/foo_pb2.py", "generated"),
        ("static/app.min.js", "generated"),
        ("vendor/github.com/x/y.go", "vendored"),
        ("src/auth/session.ts", None),
        ("README.md", None),
    ],
)
def test_classify_paths(path, reason):
    assert classify(_fd(path)) == reason


def test_classify_generated_header():
    assert classify(_fd("src/schema.ts", "// Code generated by protoc. DO NOT EDIT.")) == "generated"


def test_classify_fixture(index):
    got = {f.path: classify(f) for f in index.files}
    assert got["package-lock.json"] == "lockfile"
    assert got["docs/guide.md"] == "rename"
    assert got["assets/logo.png"] == "binary"
    assert got["src/auth/session.ts"] is None
